const LanguageContext = createContext<LanguageContextType>({
  lang: "en",
  setLang: () => {},
  t: (k) => k,
  isRTL: false,
});

function getSavedLang(): Language {
  try {
    const saved = localStorage.getItem("expatrum_lang");
    if (saved === "en" || saved === "de" || saved === "ar") return saved;
  } catch {}
  return "en";
}

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Language>(getSavedLang);
  const isRTL = lang === "ar";

  useEffect(() => {
    const html = document.documentElement;
    html.setAttribute("dir", isRTL ? "rtl" : "ltr");
    html.setAttribute("lang", lang);
  }, [lang, isRTL]);

  const setLang = (l: Language) => {
    setLangState(l);
    try { localStorage.setItem("expatrum_lang", l); } catch {}
  };

  const t = (key: string) => translations[lang][key] ?? translations["en"][key] ?? key;

  return (
    <LanguageContext.Provider value={{ lang, setLang, t, isRTL }}>
      {children}
    </LanguageContext.Provider>
  );
}

export const useLang = () => useContext(LanguageContext);
